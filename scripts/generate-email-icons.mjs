/**
 * Renders the Lucide icons used in email buttons to small PNGs and writes
 * them as base64 strings to lib/email-icons.ts.
 *
 * Email clients (Gmail especially) strip inline SVG, so the template attaches
 * these PNGs inline and references them with `cid:`. Re-run after changing
 * the icon list or colours:
 *
 *   node scripts/generate-email-icons.mjs
 *
 * Uses `sharp`, which ships with Next.js.
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

import { __iconData as phone } from "lucide-react/dist/esm/icons/phone.mjs"
import { __iconData as messageCircle } from "lucide-react/dist/esm/icons/message-circle.mjs"
import { __iconData as mail } from "lucide-react/dist/esm/icons/mail.mjs"

const ICONS = { phone, text: messageCircle, mail }
// Matches the site palette: paper on the solid button, ink on the outlined one.
const COLORS = { light: "#fafafa", dark: "#0a0a0a" }
// Rendered at 3x of the 16px display size so they stay crisp on retina screens.
const PX = 48

const toSvg = ({ node }, color) => {
  const children = node
    .map(([tag, attrs]) =>
      `<${tag} ${Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ")}/>`
    )
    .join("")
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${PX}" height="${PX}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${children}</svg>`
}

const entries = []
for (const [name, data] of Object.entries(ICONS)) {
  for (const [tone, color] of Object.entries(COLORS)) {
    const png = await sharp(Buffer.from(toSvg(data, color))).png({ compressionLevel: 9 }).toBuffer()
    entries.push(`  "${name}-${tone}": "${png.toString("base64")}",`)
  }
}

const out = `// Generated by scripts/generate-email-icons.mjs — do not edit by hand.
// Lucide icons (ISC licence) as ${PX}px PNGs, base64-encoded, for email buttons.

export const EMAIL_ICONS = {
${entries.join("\n")}
} as const

export type EmailIconName = ${Object.keys(ICONS)
  .map((n) => `"${n}"`)
  .join(" | ")}
`

const target = fileURLToPath(new URL("../lib/email-icons.ts", import.meta.url))
writeFileSync(target, out)
console.log(`Wrote ${entries.length} icons to lib/email-icons.ts`)
